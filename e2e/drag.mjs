import { chromium } from '@playwright/test';
const base = 'http://localhost:5173';
await fetch(`${base}/api/admin/reset`, { method: 'POST' });
const before = (await (await fetch(`${base}/api/state`)).json()).purchaseOrders[0].keyDates.launch;
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
await p.goto(`${base}/timeline`, { waitUntil: 'networkidle' }); await p.waitForTimeout(2500);
// Resize the QC task (auto-scheduled) by dragging its end handle to the right: +~1 week
const bar = p.locator('[data-task-id="1042-qc"] .b-gantt-task').first();
const box = await bar.boundingBox();
console.log('qc bar', box);
await p.mouse.move(box.x + box.width - 2, box.y + box.height / 2);
await p.mouse.down();
await p.mouse.move(box.x + box.width + 40, box.y + box.height / 2, { steps: 10 });
await p.mouse.move(box.x + box.width + 58, box.y + box.height / 2, { steps: 10 });
await p.mouse.up();
await p.waitForTimeout(2500);
const after = (await (await fetch(`${base}/api/state`)).json()).purchaseOrders[0].keyDates.launch;
console.log('launch before', before, 'after', after);
await p.screenshot({ path: 'e2e/shots/drag.png' });
await b.close();
